# 5. Figures
# ---------------------------------------------------------------------------
def fig_intensity_gmm(fit, base_ploidy, path, label="fluorescence intensity"):
    """Histogram of log2(measured value) overlaid with the fitted ploidy peaks."""
    x = fit["x_log2"]
    gmm, k = fit["gmm"], fit["k"]

    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.hist(x, bins=60, density=True, color="#BBBBBB",
            edgecolor="white", linewidth=0.3, label="all nuclei")

    # Smooth x-grid to draw the model's curves on.
    grid = np.linspace(x.min(), x.max(), 500).reshape(-1, 1)
    total = np.exp(gmm.score_samples(grid))                 # combined fit
    resp = gmm.predict_proba(grid)
    comp = resp * total[:, None]                            # each peak alone

    order = fit["order"]
    for rank, raw in enumerate(order, start=1):             # dim -> bright
        ax.plot(grid.ravel(), comp[:, raw], "--", lw=1.8,
                color=PALETTE[(rank - 1) % len(PALETTE)],
                label=f"class {rank} ({ploidy_label(rank, base_ploidy)})")
    ax.plot(grid.ravel(), total, "k-", lw=2.0, label="combined fit")

    ax.set_xlabel(f"log$_2$( {label} )")
    ax.set_ylabel("density")
    ax.set_title(f"Ploidy classes from {label}  (K = {k}, chosen by BIC)")
    ax.legend(fontsize=8, framealpha=0.9)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def fig_model_selection(fit, path):
    """BIC and AIC vs number of classes, with the chosen K marked."""
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(fit["Ns"], fit["bic"], "o-", color="#EE6677", label="BIC")
    ax.plot(fit["Ns"], fit["aic"], "s--", color="#4477AA", label="AIC")
    kbest = fit["Ns"][int(np.argmin(fit["bic"]))]
    ax.axvline(kbest, color="k", ls=":", lw=1)
    ax.annotate(f"chosen K = {kbest}", xy=(kbest, np.min(fit["bic"])),
                xytext=(6, 12), textcoords="offset points", fontsize=10)
    ax.set_xlabel("number of ploidy classes (K)")
    ax.set_ylabel("information criterion (lower = better)")
    ax.set_title("How many ploidy levels? Model selection")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def fig_class_percentages(df, fit, base_ploidy, path):
    """Bar chart: what % of all nuclei fall in each ploidy class."""
    counts = (df["ploidy_class"].value_counts(normalize=True)
              .sort_index() * 100)
    labels = [f"{c}\n{ploidy_label(c, base_ploidy)}" for c in counts.index]
    colors = [PALETTE[(c - 1) % len(PALETTE)] for c in counts.index]

    fig, ax = plt.subplots(figsize=(6, 4))
    bars = ax.bar(labels, counts.values, color=colors, edgecolor="black",
                  linewidth=0.5)
    ax.bar_label(bars, fmt="%.1f%%", padding=2, fontsize=10)
    ax.set_ylabel("% of nuclei")
    ax.set_xlabel("ploidy class")
    ax.set_title("Ploidy distribution across all nuclei")
    ax.set_ylim(0, counts.max() * 1.18)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def fig_within_cell(per_cell, headline, path, label="fluorescence intensity"):
    """The key figure for the multinucleate question, in two panels."""
    multi = per_cell[per_cell["n_nuclei"] >= 2]
    fig, (axL, axR) = plt.subplots(1, 2, figsize=(11, 4.4))

    # Left: how many distinct ploidy levels each cell contains.
    dist_counts = (multi["n_distinct_ploidy"].value_counts(normalize=True)
                   .sort_index() * 100)
    axL.bar([str(i) for i in dist_counts.index], dist_counts.values,
            color=["#228833" if i == 1 else "#EE6677" for i in dist_counts.index],
            edgecolor="black", linewidth=0.5)
    for i, v in zip(range(len(dist_counts)), dist_counts.values):
        axL.text(i, v + 0.8, f"{v:.0f}%", ha="center", fontsize=10)
    axL.set_xlabel("distinct ploidy levels found inside one cell")
    axL.set_ylabel("% of multinucleate cells")
    axL.set_title(f"{headline['pct_mixed_confident']:.0f}% of cells confidently MIXED\n"
                  f"(green = uniform, red = >1 ploidy class)")
    axL.set_ylim(0, max(dist_counts.values) * 1.2)

    # Right: threshold-free check. Brightest/dimmest intensity ratio per cell,
    # split by whether the model called the cell uniform or mixed. Uniform cells
    # cluster near 1 (just noise); mixed cells push toward 2x (a real doubling).
    uni = multi.loc[~multi["is_mixed"], "intensity_fold_range"]
    mix = multi.loc[multi["is_mixed"], "intensity_fold_range"]
    bins = np.linspace(1, max(3.0, multi["intensity_fold_range"].max()), 30)
    axR.hist(uni, bins=bins, alpha=0.7, color="#228833", label="uniform cells")
    axR.hist(mix, bins=bins, alpha=0.7, color="#EE6677", label="mixed cells")
    axR.axvline(2.0, color="k", ls=":", lw=1)
    axR.text(2.02, axR.get_ylim()[1] * 0.88, "2x = one\ndoubling", fontsize=8)
    axR.axvline(headline["fold_threshold"], color="#555555", ls="--", lw=1)
    axR.text(headline["fold_threshold"] + 0.02, axR.get_ylim()[1] * 0.55,
             "mixed-call\ncutoff", fontsize=8, color="#555555")
    axR.set_xlabel(f"max / min {label} of nuclei within a cell")
    axR.set_ylabel("number of cells")
    axR.set_title(f"Within-cell {label} range (no model, no threshold)")
    axR.legend()

    fig.suptitle("Do the nuclei inside a cell share a ploidy?", fontsize=13)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(path, dpi=150)
    plt.close(fig)


def fig_intensity_vs_volume(df, intensity_col, volume_col, base_ploidy, path):
    """2D sanity check: intensity vs volume, colored by ploidy class."""
    fig, ax = plt.subplots(figsize=(6, 5))
    for c in sorted(df["ploidy_class"].unique()):
        sub = df[df["ploidy_class"] == c]
        ax.scatter(sub[intensity_col], sub[volume_col], s=14, alpha=0.6,
                   color=PALETTE[(c - 1) % len(PALETTE)],
                   label=f"class {c} ({ploidy_label(c, base_ploidy)})")
    ax.set_xscale("log", base=2)
    ax.set_yscale("log", base=2)
    ax.set_xlabel("fluorescence intensity (log$_2$)")
    ax.set_ylabel("nuclear volume (log$_2$)")
    ax.set_title("Intensity vs volume, colored by ploidy class")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def fig_validation(df, base_ploidy, path):
    """If ground truth exists (demo data), show assigned class vs true ploidy."""
    ct = pd.crosstab(df["true_ploidy"], df["ploidy_label"])
    # Order the assigned-ploidy columns numerically (2C,4C,8C,16C), not as text
    # (otherwise '16C' sorts before '2C' and the diagonal looks scrambled).
    ct = ct[sorted(ct.columns, key=lambda s: int(s.rstrip("C")))]
    fig, ax = plt.subplots(figsize=(6, 4.5))
    im = ax.imshow(ct.values, cmap="Blues", aspect="auto")
    ax.set_xticks(range(len(ct.columns)), ct.columns)
    ax.set_yticks(range(len(ct.index)), [f"{p}C" for p in ct.index])
    ax.set_xlabel("ploidy assigned by the pipeline")
    ax.set_ylabel("true ploidy (ground truth)")
    ax.set_title("Validation: assigned vs true ploidy\n(should be a clean diagonal)")
    for i in range(ct.shape[0]):
        for j in range(ct.shape[1]):
            ax.text(j, i, ct.values[i, j], ha="center", va="center",
                    color="black", fontsize=9)
    fig.colorbar(im, ax=ax, label="number of nuclei")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


