"""
ploidy_pipeline.py
==================

A small, self-contained ploidy pipeline for fluorescence images of
multinucleate cells. It does the same core thing as iSPy (the collaborator's
tool) - classify each nucleus into a ploidy level from its fluorescence
intensity using a Gaussian Mixture Model - and then adds the one extra step
iSPy does not do for you: comparing the nuclei *within the same cell* to see
whether a cell's nuclei share a ploidy or not.

It is written to be readable if you are rusty with Python. Every block is
commented. You do not edit this file to use it - you pass your settings on the
command line (see the examples at the bottom of this docstring).

WHAT GOES IN
------------
A CSV where each row is ONE NUCLEUS, with at least:
  * an intensity column  (summed fluorescence = proxy for DNA = proxy for ploidy)
  * a cell-id column     (which parent cell the nucleus belongs to)
Optionally:
  * a volume column      (nuclear size - an independent check on ploidy)
  * a group/sample column (e.g. plant or genotype) to keep runs separate
  * a 'true_ploidy' column (only the demo data has this; used for validation)

WHAT COMES OUT  (all written into an output folder, default: example_outputs/)
-------------------------------------------------------------------------
  per_nucleus_classified.csv  your input + a 'ploidy_class' (1..K) and
                              'ploidy_label' (2C, 4C, ...) column per nucleus
  per_cell_summary.csv        one row per cell: how many nuclei, which ploidy
                              levels it contains, and whether it is uniform/mixed
  summary.txt                 a plain-text report of every headline number
  fig1_intensity_gmm.png      intensity histogram + the fitted ploidy peaks
  fig2_model_selection.png    BIC/AIC vs number of peaks (how K was chosen)
  fig3_class_percentages.png  % of nuclei at each ploidy level
  fig4_within_cell.png        THE key figure: do nuclei within a cell match?
  fig5_intensity_vs_volume.png  2D sanity check, points colored by ploidy class
  fig6_validation.png         (only if a true_ploidy column exists)

THE METHOD, IN ONE PARAGRAPH
----------------------------
DNA content doubles at each ploidy step (2C -> 4C -> 8C ...), and fluorescence
is proportional to DNA content. So if you take log-base-2 of intensity, the
ploidy levels become a row of evenly spaced bumps. A Gaussian Mixture Model
fits K bell curves to those bumps; each bell curve is one ploidy class. We let
the data choose K using the BIC score, then sort the classes from dimmest to
brightest and label them 1..K (class 1 = lowest ploidy). The fold-change
between neighbouring class means should come out near 2.0 if these really are
ploidy doublings - the pipeline prints that number so you can check.

EXAMPLES
--------
  # 1) Just run the built-in demo (after: python3 make_demo_data.py)
  python3 ploidy_pipeline.py

  # 2) Your own data, letting BIC choose the number of ploidy levels
  python3 ploidy_pipeline.py --csv data/my_nuclei.csv \
      --intensity-col Total_Intensity --cell-col Cell_ID \
      --volume-col Nuclear_Volume

  # 3) Force exactly 4 ploidy classes and call the lowest one 2C
  python3 ploidy_pipeline.py --csv data/my_nuclei.csv \
      --intensity-col Total_Intensity --cell-col Cell_ID \
      --n-classes 4 --base-ploidy 2
"""

