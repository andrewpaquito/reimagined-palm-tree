def parse_args():
    p = argparse.ArgumentParser(
        description="Classify nuclear ploidy from fluorescence and compare "
                    "nuclei within each cell.",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--csv", default="data/demo_nuclei.csv",
                   help="Input CSV, one row per nucleus "
                        "(default: data/demo_nuclei.csv)")
    p.add_argument("--intensity-col", default="Total_Intensity",
                   help="Column holding summed fluorescence per nucleus.")
    p.add_argument("--cell-col", default="Cell_ID",
                   help="Column identifying the parent cell of each nucleus. "
                        "Use 'none' if every nucleus is its own cell.")
    p.add_argument("--volume-col", default="Nuclear_Volume",
                   help="Optional nuclear-size column (use 'none' to skip).")
    p.add_argument("--group-col", default="none",
                   help="Optional column to analyse groups separately "
                        "(e.g. genotype). 'none' = pool everything.")
    p.add_argument("--n-classes", type=int, default=0,
                   help="Force this many ploidy classes. 0 = let BIC choose.")
    p.add_argument("--min-classes", type=int, default=1,
                   help="Smallest number of classes to try when auto-choosing.")
    p.add_argument("--max-classes", type=int, default=8,
                   help="Largest number of classes to try when auto-choosing.")
    p.add_argument("--base-ploidy", type=int, default=2,
                   help="Ploidy of the dimmest class, for labelling (2 => 2C).")
    p.add_argument("--label", default="fluorescence intensity",
                   help="Name of the measured quantity, used on figure axes/titles "
                        "(e.g. 'nuclear size' for a size-based run).")
    p.add_argument("--mixed-fold-threshold", type=float, default=1.5,
                   help="A cell is only called 'confidently mixed' if its "
                        "brightest nucleus is at least this many times brighter "
                        "than its dimmest. 1.5 sits between no-doubling (1x) and "
                        "a full doubling (2x), so it ignores within-class noise.")
    p.add_argument("--outdir", default="example_outputs",
                   help="Folder to write figures and tables into.")
    p.add_argument("--seed", type=int, default=0,
                   help="Random seed (keeps results reproducible).")
    return p.parse_args()


# ---------------------------------------------------------------------------
# 2. Load and sanity-check the data
# ---------------------------------------------------------------------------
def load_data(args):
    if not os.path.exists(args.csv):
        sys.exit(f"ERROR: input file not found: {args.csv}\n"
                 f"Tip: run `python3 make_demo_data.py` first to create the demo.")

    # Most CSVs are comma-separated, but some European tools (and ilastik in
    # some locales) use semicolons. Try comma, fall back to semicolon.
    df = pd.read_csv(args.csv)
    if df.shape[1] == 1:
        df = pd.read_csv(args.csv, sep=";")

    if args.intensity_col not in df.columns:
        sys.exit(f"ERROR: intensity column '{args.intensity_col}' not in CSV.\n"
                 f"Columns found: {list(df.columns)}\n"
                 f"Set the right one with --intensity-col.")

    # Drop rows with missing or non-positive intensity (can't take log of those).
    n0 = len(df)
    df = df[df[args.intensity_col].notna()]
    df = df[df[args.intensity_col] > 0].copy()
    if len(df) < n0:
        print(f"  note: dropped {n0 - len(df)} rows with missing/<=0 intensity")

    # If there is no real cell column, make every nucleus its own cell so the
    # rest of the code still runs (the within-cell figure just won't be useful).
    if args.cell_col.lower() == "none" or args.cell_col not in df.columns:
        if args.cell_col.lower() != "none":
            print(f"  note: cell column '{args.cell_col}' not found - treating "
                  f"each nucleus as its own cell (no within-cell comparison).")
        args.cell_col = "_cell_id_auto"
        df[args.cell_col] = np.arange(1, len(df) + 1)

    return df


# ---------------------------------------------------------------------------
# 3. The ploidy model: fit Gaussian mixture on log2(intensity)
# ---------------------------------------------------------------------------
def fit_ploidy_gmm(intensity, args):
    """
    Fit a Gaussian Mixture Model to log2(intensity) and return everything we
    need to describe and plot the ploidy classes.

    Returns a dict with:
      k            chosen number of classes
      class_id     array, the ploidy class (1..k) for each input nucleus
      means_log2   sorted class means in log2 space (low -> high)
      fold_change  ratio between neighbouring class means in real units (~2 hoped)
      Ns, bic, aic the model-selection curves (for the BIC/AIC figure)
      x_log2       the log2-transformed intensities (handy for plotting)
    """
    # The single most important line: move to log-2 space, where ploidy
    # doublings become equal steps. reshape(-1, 1) makes it a column, which is
    # the shape scikit-learn expects.
    x_log2 = np.log2(np.asarray(intensity, dtype=float)).reshape(-1, 1)

    # Decide which numbers of classes (K) to consider.
    if args.n_classes and args.n_classes > 0:
        candidate_Ns = [args.n_classes]          # user forced a specific K
    else:
        hi = min(args.max_classes, len(x_log2))  # never ask for more classes than points
        candidate_Ns = list(range(args.min_classes, hi + 1))

    Ns, bic, aic, models = [], [], [], []
    for n in candidate_Ns:
        gmm = GaussianMixture(
            n_components=n,
            covariance_type="full",   # in 1D all covariance types are equivalent
            n_init=10,                # restart 10x and keep the best fit (stability)
            max_iter=500,
            random_state=args.seed,
        ).fit(x_log2)
        Ns.append(n)
        bic.append(gmm.bic(x_log2))  # Bayesian Information Criterion: lower = better
        aic.append(gmm.aic(x_log2))  # Akaike Information Criterion: lower = better
        models.append(gmm)

    # Pick the model with the smallest BIC (this is "let the data choose K").
    best = int(np.argmin(bic))
    gmm = models[best]
    k = Ns[best]

    # gmm.predict gives each nucleus a component number, but those numbers are
    # in arbitrary order. We re-rank them by their mean so that class 1 is
    # always the dimmest (lowest ploidy) and class k the brightest.
    raw_labels = gmm.predict(x_log2)
    means = gmm.means_.ravel()
    order = np.argsort(means)                 # raw component indices, dim -> bright
    rank_of_raw = np.empty(k, dtype=int)
    rank_of_raw[order] = np.arange(1, k + 1)  # map raw component -> class 1..k
    class_id = rank_of_raw[raw_labels]

    means_log2 = np.sort(means)               # class means, log2 space, ascending
    means_real = 2.0 ** means_log2            # the same means back in real units
    fold_change = means_real[1:] / means_real[:-1]   # neighbour ratios (~2 hoped)

    return dict(k=k, class_id=class_id, means_log2=means_log2,
                means_real=means_real, fold_change=fold_change,
                Ns=np.array(Ns), bic=np.array(bic), aic=np.array(aic),
                x_log2=x_log2.ravel(), gmm=gmm, order=order)


def ploidy_label(class_id, base_ploidy):
    """Turn class number 1,2,3,... into a ploidy label '2C','4C','8C',...

    Assumes each class up is one DNA doubling (the thing fold_change checks).
    """
    return f"{base_ploidy * (2 ** (class_id - 1))}C"


# ---------------------------------------------------------------------------
# 4. Within-cell analysis: do the nuclei inside one cell share a ploidy?
# ---------------------------------------------------------------------------
def within_cell_analysis(df, cell_col, intensity_col, fold_threshold=1.5):
    """
    Build one row per cell describing its nuclei, and return that table plus a
    few headline numbers.

    Two ways of calling a cell 'mixed':
      is_mixed            its nuclei landed in more than one ploidy CLASS. Simple
                          and matches iSPy, but a tiny bit jumpy: a nucleus that
                          sits right on a class boundary can flip a truly uniform
                          cell to 'mixed' just from measurement noise.
      is_mixed_confident  the above AND the brightest nucleus is >= fold_threshold
                          times the dimmest. This ignores within-class wobble and
                          only flags cells with a real intensity gap. Report THIS
                          one as your headline; report is_mixed for completeness.

    We also keep intensity_fold_range (brightest/dimmest), a model-free,
    threshold-free number: uniform cells sit near 1, real doublings near 2+.
    """
    records = []
    for cell, sub in df.groupby(cell_col):
        classes = sub["ploidy_class"].to_numpy()
        inten = sub[intensity_col].to_numpy()
        distinct = np.unique(classes)
        fold_range = float(inten.max() / inten.min())
        records.append({
            cell_col: cell,
            "n_nuclei": len(sub),
            "n_distinct_ploidy": len(distinct),
            "min_class": int(classes.min()),
            "max_class": int(classes.max()),
            "class_spread": int(classes.max() - classes.min()),
            "is_mixed": len(distinct) > 1,
            "is_mixed_confident": (len(distinct) > 1) and (fold_range >= fold_threshold),
            "ploidy_labels": ",".join(sorted(set(sub["ploidy_label"]))),
            "intensity_fold_range": fold_range,
        })
    per_cell = pd.DataFrame(records)

    multi = per_cell[per_cell["n_nuclei"] >= 2]   # only multinucleate cells count
    headline = {
        "n_cells": len(per_cell),
        "n_multinucleate": len(multi),
        "n_mixed": int(multi["is_mixed"].sum()),
        "pct_mixed": (100.0 * multi["is_mixed"].mean()) if len(multi) else 0.0,
        "n_mixed_confident": int(multi["is_mixed_confident"].sum()),
        "pct_mixed_confident": (100.0 * multi["is_mixed_confident"].mean()) if len(multi) else 0.0,
        "fold_threshold": fold_threshold,
        "median_fold_uniform": float(
            multi.loc[~multi["is_mixed"], "intensity_fold_range"].median())
            if (~multi["is_mixed"]).any() else float("nan"),
        "median_fold_mixed": float(
            multi.loc[multi["is_mixed"], "intensity_fold_range"].median())
            if multi["is_mixed"].any() else float("nan"),
    }
    return per_cell, headline


