# 6. Tie it all together
# ---------------------------------------------------------------------------
def run_one(df, label, args, outdir):
    """Run the whole analysis on one dataframe (one group) and write outputs."""
    print(f"\n=== Analysing: {label}  ({len(df)} nuclei, "
          f"{df[args.cell_col].nunique()} cells) ===")

    fit = fit_ploidy_gmm(df[args.intensity_col].to_numpy(), args)
    df = df.copy()
    df["ploidy_class"] = fit["class_id"]
    df["ploidy_label"] = [ploidy_label(c, args.base_ploidy) for c in fit["class_id"]]

    fold_txt = ", ".join(f"{f:.2f}x" for f in fit["fold_change"])
    print(f"  chosen K (ploidy levels): {fit['k']}")
    print(f"  fold-change between neighbouring classes: {fold_txt}")
    print(f"  (values near 2.0 confirm these are real ploidy doublings)")

    per_cell, headline = within_cell_analysis(
        df, args.cell_col, args.intensity_col, args.mixed_fold_threshold)
    print(f"  multinucleate cells: {headline['n_multinucleate']}")
    print(f"  MIXED by class only            : {headline['n_mixed']} "
          f"({headline['pct_mixed']:.1f}%)")
    print(f"  MIXED confidently (>= {args.mixed_fold_threshold}x gap): "
          f"{headline['n_mixed_confident']} "
          f"({headline['pct_mixed_confident']:.1f}%)  <- report this one")

    # ---- write tables ----
    df.to_csv(os.path.join(outdir, "per_nucleus_classified.csv"), index=False)
    per_cell.to_csv(os.path.join(outdir, "per_cell_summary.csv"), index=False)

    # ---- write the figures ----
    fig_intensity_gmm(fit, args.base_ploidy,
                      os.path.join(outdir, "fig1_intensity_gmm.png"), args.label)
    fig_model_selection(fit, os.path.join(outdir, "fig2_model_selection.png"))
    fig_class_percentages(df, fit, args.base_ploidy,
                          os.path.join(outdir, "fig3_class_percentages.png"))
    # The within-cell figure only makes sense if some cells actually hold >=2
    # nuclei. With --cell-col none every nucleus is its own cell, so we skip it.
    if headline["n_multinucleate"] > 0:
        fig_within_cell(per_cell, headline,
                        os.path.join(outdir, "fig4_within_cell.png"), args.label)
    else:
        print("  (no multinucleate cells -> skipping the within-cell figure)")
    if args.volume_col != "none" and args.volume_col in df.columns:
        fig_intensity_vs_volume(df, args.intensity_col, args.volume_col,
                                args.base_ploidy,
                                os.path.join(outdir, "fig5_intensity_vs_volume.png"))
    if "true_ploidy" in df.columns:
        fig_validation(df, args.base_ploidy,
                       os.path.join(outdir, "fig6_validation.png"))

    # ---- write the plain-text report ----
    write_summary(df, fit, per_cell, headline, args,
                  os.path.join(outdir, "summary.txt"))
    return df, per_cell, headline, fit


def write_summary(df, fit, per_cell, headline, args, path):
    lines = []
    lines.append("PLOIDY PIPELINE - SUMMARY REPORT")
    lines.append("=" * 50)
    lines.append(f"Input file        : {args.csv}")
    lines.append(f"Nuclei analysed   : {len(df)}")
    lines.append(f"Cells analysed    : {df[args.cell_col].nunique()}")
    lines.append("")
    lines.append("PLOIDY CLASSES (from the Gaussian Mixture Model)")
    lines.append("-" * 50)
    lines.append(f"Number of classes chosen by BIC : {fit['k']}")
    for c in range(1, fit["k"] + 1):
        n = int((df["ploidy_class"] == c).sum())
        pct = 100.0 * n / len(df)
        lines.append(f"  class {c} ({ploidy_label(c, args.base_ploidy):>4}): "
                     f"{n:5d} nuclei ({pct:5.1f}%)   "
                     f"mean intensity = {fit['means_real'][c-1]:.1f}")
    fold_txt = ", ".join(f"{f:.2f}x" for f in fit["fold_change"])
    lines.append(f"Fold-change between neighbouring classes: {fold_txt}")
    lines.append("  (near 2.0 => the classes really are ploidy doublings)")
    lines.append("")
    lines.append("WITHIN-CELL PLOIDY (your multinucleate question)")
    lines.append("-" * 50)
    lines.append(f"Multinucleate cells (>=2 nuclei) : {headline['n_multinucleate']}")
    lines.append(f"  mixed by ploidy class alone     : {headline['n_mixed']} "
                 f"({headline['pct_mixed']:.1f}%)")
    lines.append(f"  mixed AND >= {headline['fold_threshold']}x intensity gap : "
                 f"{headline['n_mixed_confident']} "
                 f"({headline['pct_mixed_confident']:.1f}%)  <-- headline number")
    lines.append("  (the second, stricter count ignores nuclei that only just")
    lines.append("   crossed a class boundary because of measurement noise.)")
    lines.append(f"Median brightest/dimmest ratio, uniform cells: "
                 f"{headline['median_fold_uniform']:.2f}  (near 1 = no real gap)")
    lines.append(f"Median brightest/dimmest ratio, mixed cells  : "
                 f"{headline['median_fold_mixed']:.2f}  (near/above 2 = a doubling)")
    if "true_ploidy" in df.columns:
        acc = (df["ploidy_label"].str.rstrip("C").astype(int)
               == df["true_ploidy"]).mean() * 100
        lines.append("")
        lines.append("VALIDATION (demo data only)")
        lines.append("-" * 50)
        lines.append(f"Per-nucleus ploidy called correctly: {acc:.1f}%")
    text = "\n".join(lines)
    with open(path, "w") as fh:
        fh.write(text + "\n")
    print("\n" + text)


def main():
    args = parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    df = load_data(args)

    print(textwrap.dedent(f"""
    Loaded {len(df)} nuclei from {args.csv}
      intensity column : {args.intensity_col}
      cell column      : {args.cell_col}
      volume column    : {args.volume_col}
    """).rstrip())

    # If a group column was given, analyse each group into its own subfolder.
    if args.group_col != "none" and args.group_col in df.columns:
        for g, sub in df.groupby(args.group_col):
            sub_out = os.path.join(args.outdir, f"group_{g}")
            os.makedirs(sub_out, exist_ok=True)
            run_one(sub, str(g), args, sub_out)
    else:
        run_one(df, "all data", args, args.outdir)

    print(f"\nDone. Open the '{args.outdir}/' folder for figures and tables.")


if __name__ == "__main__":
    main()
